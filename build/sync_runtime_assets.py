#!/usr/bin/env python3
'''Generate Codex and Gemini adapters from the canonical Claude definitions.

The gemini runtime targets Antigravity CLI (agy), Gemini CLI's successor: its
agents use agy's tool names, and each command becomes a skill, since a skill is
agy's slash command.

The Markdown bodies in agents/ and commands/ remain the source of truth. This
script translates only the runtime manifest layer: file format, tool names,
and argument injection.

Codex adapters carry no sandbox or approval keys. Per the Codex subagents docs
(https://learn.chatgpt.com/docs/agent-configuration/subagents, read 2026-11-12,
not probed locally), a custom agent file's sandbox_mode, approval_policy,
model_provider and mcp_servers do not override the parent session: a subagent
inherits the parent turn's sandbox and approvals. No documented key makes one
agent read-only (features.shell_tool = false removes the shell these agents
need, and no documented key turns off apply_patch), and PreToolUse hook input
carries no agent_type.
So a Codex read-only agent's contract is instruction-only; only the parent
session's sandbox (for example codex --sandbox read-only) enforces it.

Run:
  uv run --with pyyaml python build/sync_runtime_assets.py
  uv run --with pyyaml python build/sync_runtime_assets.py --check
'''
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

from check_frontmatter import AGENT_RESTRICTION_RE, MCP_TOOL_PREFIX, split_tools


REPO = Path(__file__).resolve().parent.parent
CANONICAL_AGENTS = REPO / 'agents'
CANONICAL_COMMANDS = REPO / 'commands'
CODEX_AGENTS = REPO / 'runtimes' / 'codex' / 'agents'
GEMINI_AGENTS = REPO / 'runtimes' / 'gemini' / 'agents'
GEMINI_SKILLS = REPO / 'runtimes' / 'gemini' / 'skills'
GENERATED_DIRS = (CODEX_AGENTS, GEMINI_AGENTS, GEMINI_SKILLS)

# agy's tool names, from its built-in migrate-agent-settings converter; each name
# was probed with agy 1.2.17 on 2026-11-12. agy has no search tool, so Grep and
# Glob fold into read_file, and Bash brings manage_task beside run_command.
TOOL_MAP: dict[str, tuple[str, ...]] = {
  'Read': ('read_file',),
  'Write': ('write_file',),
  'Edit': ('edit_file',),
  'Grep': ('read_file',),
  'Glob': ('read_file',),
  'Bash': ('run_command', 'manage_task'),
  'WebFetch': ('search_web',),
  'WebSearch': ('search_web',),
}
COMMAND_ARGUMENTS = (
  "Take the argument from the user's message: the text after `/{name}`, or the "
  'target the user named when this skill loaded on its own.'
)
GENERATED_COMMENT = '# Generated by build/sync_runtime_assets.py; do not edit by hand.\n'


def read_frontmatter(path: Path) -> tuple[dict, str]:
  text = path.read_text()
  match = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
  if not match:
    raise ValueError(f'{path}: no frontmatter block')
  frontmatter = yaml.safe_load(match.group(1))
  if not isinstance(frontmatter, dict):
    raise ValueError(f'{path}: frontmatter is not a mapping')
  return frontmatter, match.group(2).lstrip('\n')


def portable_name(name: str) -> str:
  return name.lower().replace(' ', '-')


def portable_description(description: str) -> str:
  # Claude's Explore entry intentionally documents a runtime-specific model
  # pin and built-in override. Neither statement is true in Codex or Gemini.
  return re.sub(
    r'\s*Haiku-pinned override of the built-in Explore agent\.?$',
    '',
    description,
  )


def canonical_tools(value: object) -> list[str]:
  if value is None:
    return []
  return split_tools(value)


def claude_only_tool(tool: str) -> bool:
  '''Agent and MCP tools have no Gemini equivalent here: Gemini names MCP
  tools by its own configured servers and has no Agent restriction form.'''
  return tool.startswith(MCP_TOOL_PREFIX) or AGENT_RESTRICTION_RE.fullmatch(tool) is not None


def render_codex_agent(path: Path) -> str:
  frontmatter, body = read_frontmatter(path)
  name = portable_name(str(frontmatter['name']))
  description = portable_description(str(frontmatter['description']))
  lines = [
    GENERATED_COMMENT.rstrip(),
    f'name = {json.dumps(name, ensure_ascii=False)}',
    f'description = {json.dumps(description, ensure_ascii=False)}',
    f'developer_instructions = {json.dumps(body, ensure_ascii=False)}',
  ]
  return '\n'.join(lines) + '\n'


def render_gemini_agent(path: Path) -> str:
  frontmatter, body = read_frontmatter(path)
  tools, dropped = [], []
  for tool in canonical_tools(frontmatter.get('tools')):
    if claude_only_tool(tool):
      dropped.append(tool)
      continue
    try:
      tools.extend(TOOL_MAP[tool])
    except KeyError as exc:
      raise ValueError(f'{path}: no Gemini mapping for tool {tool!r}') from exc
  # No subagent or mainAgent key: either one hides the agent in ~/.gemini/agents
  # (probed 2026-11-12), so these stay session agents (agy --agent <name>).
  adapted = {
    'name': portable_name(str(frontmatter['name'])),
    'description': portable_description(str(frontmatter['description'])),
    'kind': 'local',
    'tools': list(dict.fromkeys(tools)),
  }
  yaml_text = yaml.safe_dump(
    adapted,
    sort_keys=False,
    allow_unicode=True,
    width=1000,
  ).rstrip()
  if dropped:
    yaml_text += f'\n# Claude-only tools dropped (no Gemini mapping): {", ".join(dropped)}'
  return f'---\n{yaml_text}\n---\n\n{body}'


def render_gemini_command_skill(path: Path) -> str:
  '''A command as an agy skill: the folder name is the slash command.'''
  frontmatter, body = read_frontmatter(path)
  adapted = {'name': path.stem, 'description': str(frontmatter['description'])}
  yaml_text = yaml.safe_dump(
    adapted,
    sort_keys=False,
    allow_unicode=True,
    width=1000,
  ).rstrip()
  arguments = COMMAND_ARGUMENTS.format(name=path.stem)
  return f'---\n{GENERATED_COMMENT}{yaml_text}\n---\n\n{body.rstrip()}\n\n{arguments}\n'


def expected_assets() -> dict[Path, str]:
  expected: dict[Path, str] = {}
  for source in sorted(CANONICAL_AGENTS.glob('*.md')):
    expected[CODEX_AGENTS / f'{source.stem}.toml'] = render_codex_agent(source)
    expected[GEMINI_AGENTS / source.name] = render_gemini_agent(source)
  for source in sorted(CANONICAL_COMMANDS.glob('*.md')):
    expected[GEMINI_SKILLS / source.stem / 'SKILL.md'] = render_gemini_command_skill(source)
  return expected


def stale_generated_files(expected: dict[Path, str]) -> set[Path]:
  actual = {
    path
    for directory in GENERATED_DIRS
    if directory.exists()
    for path in directory.rglob('*')
    if path.is_file()
  }
  return actual - set(expected)


def remove_empty_folders(directory: Path) -> None:
  '''Remove a stale skill's emptied folder, up to its generated directory.'''
  while directory not in GENERATED_DIRS and not any(directory.iterdir()):
    directory.rmdir()
    print(f'removed stale {directory.relative_to(REPO)}')
    directory = directory.parent


def check(expected: dict[Path, str]) -> int:
  errors = []
  for path, content in expected.items():
    if not path.exists():
      errors.append(f'missing: {path.relative_to(REPO)}')
    elif path.read_text() != content:
      errors.append(f'out of date: {path.relative_to(REPO)}')
  errors.extend(
    f'stale: {path.relative_to(REPO)}'
    for path in sorted(stale_generated_files(expected))
  )
  for error in errors:
    print(error)
  return 1 if errors else 0


def write(expected: dict[Path, str]) -> int:
  for path, content in expected.items():
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(f'wrote {path.relative_to(REPO)}')
  for path in sorted(stale_generated_files(expected)):
    path.unlink()
    print(f'removed stale {path.relative_to(REPO)}')
    remove_empty_folders(path.parent)
  return 0


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('--check', action='store_true', help='report drift without writing')
  args = parser.parse_args(argv)
  expected = expected_assets()
  return check(expected) if args.check else write(expected)


if __name__ == '__main__':
  sys.exit(main())
